//! Element identity ([element model §1](https://github.com/hito-project/hito/blob/main/docs/architecture/element-model.md#1-identity-128-bit-ids-generated-locally)).
//!
//! Every element has an [`ElementId`]: a 128-bit UUID that never changes for
//! the life of the element, across saves, sessions, copies and exports.

use std::fmt;
use std::str::FromStr;

use uuid::Uuid;

/// The identity of an element: a 128-bit UUID.
///
/// New IDs are UUID version 7 ([RFC 9562]). They start with a millisecond
/// timestamp followed by random bits, so:
///
/// - **No server is needed.** Each copy of HITO generates IDs on its own, and
///   two copies working offline won't produce the same ID. This is what keeps
///   future multi-user editing (E20) free of ID conflicts.
/// - **IDs created close in time sort together**, which keeps storage indexes
///   compact. IDs generated by one process are strictly increasing.
///
/// An ID read back from a file or an import can be any 128-bit value, not
/// only version 7, so [`ElementId::from_u128`] and [`ElementId::from_bytes`]
/// accept every value unchanged.
///
/// **What is persisted and exported.** The 128-bit value, as
/// [`to_bytes`](ElementId::to_bytes) (16 bytes, big-endian) or as
/// [`as_u128`](ElementId::as_u128). It maps one to one to an IFC `GlobalId`,
/// which is the same 128 bits in a 22-character encoding; the IFC adapter
/// owns that encoding. The [`Display`](fmt::Display) form is the standard
/// hyphenated UUID text, for logs, debugging and text formats.
///
/// [RFC 9562]: https://www.rfc-editor.org/rfc/rfc9562
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct ElementId(Uuid);

impl ElementId {
    /// Generates a new, globally unique ID (UUID version 7).
    pub fn generate() -> Self {
        Self(Uuid::now_v7())
    }

    /// The ID with this 128-bit value.
    pub const fn from_u128(value: u128) -> Self {
        Self(Uuid::from_u128(value))
    }

    /// The ID's 128-bit value.
    pub const fn as_u128(self) -> u128 {
        self.0.as_u128()
    }

    /// The ID stored in these 16 bytes, most significant byte first.
    pub const fn from_bytes(bytes: [u8; 16]) -> Self {
        Self(Uuid::from_bytes(bytes))
    }

    /// The ID's 16 bytes, most significant byte first. This is the form a
    /// storage adapter persists: byte order matches [`Ord`], so sorted bytes
    /// are sorted IDs.
    pub const fn to_bytes(self) -> [u8; 16] {
        *self.0.as_bytes()
    }
}

impl fmt::Display for ElementId {
    /// Writes the standard hyphenated UUID form, such as
    /// `0192b5d4-6f1e-7c3a-9a4b-1f2e3d4c5b6a`.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        self.0.hyphenated().fmt(f)
    }
}

impl fmt::Debug for ElementId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "ElementId({self})")
    }
}

impl FromStr for ElementId {
    type Err = ParseElementIdError;

    /// Reads the text written by [`Display`](fmt::Display). The other common
    /// UUID forms (no hyphens, braces, `urn:uuid:`) are also accepted.
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        Uuid::parse_str(s)
            .map(Self)
            .map_err(|_| ParseElementIdError)
    }
}

/// The text given to [`ElementId::from_str`] isn't a UUID.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ParseElementIdError;

impl fmt::Display for ParseElementIdError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("not a UUID")
    }
}

impl std::error::Error for ParseElementIdError {}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;
    use std::thread;

    #[test]
    fn new_ids_are_uuid_version_7() {
        assert_eq!(ElementId::generate().0.get_version_num(), 7);
    }

    #[test]
    fn ids_from_one_process_are_strictly_increasing() {
        let ids: Vec<_> = (0..10_000).map(|_| ElementId::generate()).collect();
        assert!(ids.windows(2).all(|pair| pair[0] < pair[1]));
    }

    /// Several threads stand in for several copies of HITO generating IDs at
    /// the same moment with no coordination. None of them may clash.
    #[test]
    fn ids_generated_concurrently_never_clash() {
        let batches: Vec<Vec<ElementId>> = thread::scope(|scope| {
            let workers: Vec<_> = (0..8)
                .map(|_| scope.spawn(|| (0..20_000).map(|_| ElementId::generate()).collect()))
                .collect();
            workers.into_iter().map(|w| w.join().unwrap()).collect()
        });
        let all: HashSet<_> = batches.iter().flatten().collect();
        assert_eq!(all.len(), 8 * 20_000);
    }

    #[test]
    fn bytes_round_trip_and_keep_the_order() {
        let a = ElementId::generate();
        let b = ElementId::generate();
        assert_eq!(ElementId::from_bytes(a.to_bytes()), a);
        assert_eq!(a.cmp(&b), a.to_bytes().cmp(&b.to_bytes()));
    }

    #[test]
    fn any_128_bit_value_round_trips_unchanged() {
        // Not version 7: an ID from an older file or an imported GlobalId.
        for value in [0, 1, u128::MAX, 0x0123_4567_89ab_cdef_fedc_ba98_7654_3210] {
            let id = ElementId::from_u128(value);
            assert_eq!(id.as_u128(), value);
            assert_eq!(ElementId::from_bytes(id.to_bytes()), id);
            assert_eq!(id.to_string().parse::<ElementId>(), Ok(id));
        }
    }

    #[test]
    fn text_is_the_standard_hyphenated_form() {
        let id = ElementId::from_u128(0x0192_b5d4_6f1e_7c3a_9a4b_1f2e_3d4c_5b6a);
        assert_eq!(id.to_string(), "0192b5d4-6f1e-7c3a-9a4b-1f2e3d4c5b6a");
        assert_eq!(
            format!("{id:?}"),
            "ElementId(0192b5d4-6f1e-7c3a-9a4b-1f2e3d4c5b6a)"
        );
        assert_eq!("0192b5d46f1e7c3a9a4b1f2e3d4c5b6a".parse(), Ok(id));
        assert_eq!("C12".parse::<ElementId>(), Err(ParseElementIdError));
    }
}
